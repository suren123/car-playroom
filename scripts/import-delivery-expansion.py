"""Archive the uploaded originals and copy only approved assets to public; no pixel edits."""
import argparse
import hashlib
import json
import shutil
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/illustrations/delivery-expansion'
PUBLIC = ROOT / 'public/assets/illustrations/delivery-v2'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--upload-dir', type=Path)
    args = parser.parse_args()
    entries = json.loads((SOURCE / 'import-map.json').read_text(encoding='utf-8'))
    (SOURCE / 'originals').mkdir(parents=True, exist_ok=True)
    PUBLIC.mkdir(parents=True, exist_ok=True)
    report = []
    for item in entries:
        original = SOURCE / 'originals' / item['file']
        if not original.exists():
            if args.upload_dir is None:
                raise SystemExit(f"Missing original: {original.name}; specify --upload-dir")
            shutil.copyfile(args.upload_dir / item['upload'], original)
        with Image.open(original) as image:
            image.load()
            alpha = image.convert('RGBA').getchannel('A')
            bounds = alpha.getbbox()
            if bounds is None or alpha.getextrema()[0] != 0:
                raise SystemExit(f"Missing artwork or transparency: {original.name}")
            entry = {**item, 'size': list(image.size), 'visibleBounds': list(bounds),
                     'bytes': original.stat().st_size, 'sha256': hashlib.sha256(original.read_bytes()).hexdigest()}
        if item['enabled']:
            shutil.copyfile(original, PUBLIC / item['file'])
        report.append(entry)
    (SOURCE / 'manifest.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    active = [x for x in report if x['enabled']]
    # Use a vector display window to ignore transparent margins. Original PNG
    # bytes stay untouched, while narrow cargo and wide buildings fit equally.
    frames = {}
    for item in active:
        left, top, right, bottom = item['visibleBounds']
        left, top = max(0, left-4), max(0, top-4)
        right, bottom = min(item['size'][0], right+4), min(item['size'][1], bottom+4)
        frames[item['file'][:-4]] = {'width': item['size'][0], 'height': item['size'][1],
                                    'viewBox': f'{left} {top} {right-left} {bottom-top}'}
    (ROOT / 'games/delivery/illustration-frames.ts').write_text(
        '// Generated by scripts/import-delivery-expansion.py; PNG originals remain unchanged.\n'
        'export const deliveryIllustrationFrames:Record<string,{width:number;height:number;viewBox:string}> = '
        + json.dumps(frames, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(f"Archived {len(report)} original PNGs; enabled {len(active)} ({sum(x['bytes'] for x in active):,} bytes).")

if __name__ == '__main__':
    main()
