import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {pbkdf2Sync} from 'node:crypto';
import {familyGate,createSession,validSession,COOKIE,MAX_AGE} from '../lib/family-auth.ts';
const env=Object.fromEntries(readFileSync(new URL('../.dev.vars',import.meta.url),'utf8').trim().split('\n').map(line=>{const at=line.indexOf('=');return [line.slice(0,at),line.slice(at+1)];}));
const testPassword='local-test-only';
env.FAMILY_PASSWORD_HASH=pbkdf2Sync(testPassword,env.FAMILY_PASSWORD_SALT,100000,32,'sha256').toString('base64url');
const origin='https://family.example';
const post=(body,from=origin)=>new Request(origin+'/api/login',{method:'POST',headers:{origin:from,'content-type':'application/json'},body:JSON.stringify(body)});
const root=await familyGate(new Request(origin+'/'),env);assert.equal(root.status,307);assert.equal(root.headers.get('location'),'/game');
assert.equal(await familyGate(new Request(origin+'/login'),env),null);
assert.equal((await familyGate(new Request(origin+'/game'),env)).status,303);
assert.equal((await familyGate(new Request(origin+'/game'),env)).headers.get('location'),'/login');
assert.equal((await familyGate(new Request(origin+'/game?_rsc=test'),env)).status,303);
assert.equal((await familyGate(new Request(origin+'/api/session'),env)).status,401);
assert.equal((await familyGate(new Request(origin+'/api/records'),env)).status,401);
assert.equal((await familyGate(post({username:'parent',password:testPassword},'https://other.example'),env)).status,403);
assert.equal((await familyGate(post({username:'parent',password:'wrong'}),env)).status,401);
assert.equal((await familyGate(post({username:'other',password:testPassword}),env)).status,401);
assert.equal((await familyGate(post({username:'parent',password:testPassword}),{})).status,503);
assert.equal((await familyGate(post(null),env)).status,400);
const response=await familyGate(post({username:'parent',password:testPassword}),env);
assert.equal(response.status,200); const cookie=response.headers.get('set-cookie');
assert.match(cookie,/HttpOnly/);assert.match(cookie,/Secure/);assert.match(cookie,/SameSite=Strict/);
for(const path of ['/%67ame','/game/','/unknown','/api/session']){const denied=await familyGate(new Request(origin+path),env);assert.ok(denied.status===303||denied.status===401);}
const signedRequest=new Request(origin+'/game',{headers:{cookie:cookie.split(';')[0]}});
assert.equal(await validSession(signedRequest,env),true);assert.equal(await familyGate(signedRequest,env),null);
const now=Date.now();const signed=await createSession(env,now);
assert.equal(await validSession(new Request(origin+'/game',{headers:{cookie:COOKIE+'='+signed+'broken'}}),env),false);
assert.equal(await validSession(new Request(origin+'/game',{headers:{cookie:COOKIE+'='+signed}}),env,now+(MAX_AGE+1)*1000),false);
assert.equal(await validSession(new Request(origin+'/game',{headers:{cookie:COOKIE+'=parent.123.x.bad'}}),env),false);
const logout=await familyGate(new Request(origin+'/api/logout',{method:'POST',headers:{origin}}),env);assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
console.log('PASS: direct navigation and RSC protection, API auth, wrong credentials, missing config, CSRF, malformed body, signed session, tampering, expiry and logout.');
